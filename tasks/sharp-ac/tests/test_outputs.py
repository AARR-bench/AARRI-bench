        r"produced\s+by\s+(an?\s+)?(ai|llm|language\s+model|chatgpt|gpt)",
        r"(appears?|seems?|looks?)\s+(to\s+be\s+|like\s+)(it\s+(was|is)\s+)?(ai|llm|machine|auto).generated",
        r"(chatgpt|gpt|llm|large\s+language\s+model)",
